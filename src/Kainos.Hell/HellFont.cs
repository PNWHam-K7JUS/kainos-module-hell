        // the columns a character is sent as: each 14 pixels, bit 0 the bottom (the first sent); a blank before and after
        public static List<ushort> Columns(char c)
        {
            List<ushort> cols = new List<ushort>();
            if (c == ' ' || c == '\n' || c == '\r' || c == '\t') { for (int i = 0; i < 5; i++) cols.Add(0); return cols; }
            if (c > '~' || c < '!') return cols;        // nothing outside ! - ~
            byte[] g = Glyphs[c - '!'];
            cols.Add(0);
            List<ushort> body = new List<ushort>();
            for (int x = 0; x < 5; x++)
            {
                ushort col = 0;
                for (int r = 0; r < 7; r++)
                    if ((g[r] & (0x10 >> x)) != 0)
                    {
                        int bottom = 6 - r;                 // font row 6 (the lowest) is pixels 0 and 1
                        col |= (ushort)(3 << (2 * bottom));
                    }
                body.Add(col);
            }
            while (body.Count > 0 && body[0] == 0) body.RemoveAt(0);
            while (body.Count > 0 && body[body.Count - 1] == 0) body.RemoveAt(body.Count - 1);
            cols.AddRange(body);
            cols.Add(0);
            return cols;
        }
