The font Kainos sends Hell in: a 5 by 7 font of its own, each row doubled to fill the 14-pixel column, proportional
(blank columns at the sides trimmed). A character is sent as a blank column, its columns, and a blank column; a space
is 5 blank columns. Rows are listed top to bottom, bit 4 the leftmost pixel.

